// =============================================================================
// 全国大学生嵌入式芯片与系统设计竞赛 - 选题一 (J280 姿态控制系统竞赛套件)
// 模块名称: clk_mgr
// 目标芯片: 高云 GW2A-LV55PG484C8/I7
// 功能描述: 时钟与复位管理模块（不使用 PLL）
//           1. 系统时钟直接由外部 50MHz 晶振缓冲而来
//           2. 外部异步复位采用异步置位、同步释放，释放沿打 8 拍同步链
//           3. 输出各时钟域复位，保证上电时序确定
//           4. 板载复位键并入同一条链的异步清零端，二者释放沿都经过同步
// =============================================================================

`timescale 1ns / 1ps

module clk_mgr #(
    // 同步释放链级数，决定复位释放后输出稳定所需的拍数
    parameter RST_SYNC_CYCLES = 8
)(
    input  wire clk_50m,     // M19, 50MHz 输入
    input  wire rst_n,       // AB3, 异步低有效
    // -------------------------------------------------------------------------
    // 外部"复位"按键请求，低有效，高 = 不复位
    // -------------------------------------------------------------------------
    input  wire ext_rst_n,
    output wire clk_sys,     // 系统时钟，= clk_50m
    output wire rst_sys_n    // 同步释放后的复位，低有效，释放后至少稳定 RST_SYNC_CYCLES 拍
);

    // -------------------------------------------------------------------------
    // 系统时钟：直接旁路 50MHz 输入，不使用 PLL、不使用任何 IP 核。
    // -------------------------------------------------------------------------
    assign clk_sys = clk_50m;

    // -------------------------------------------------------------------------
    // 复位同步释放链：RST_SYNC_CYCLES 级移位寄存器
    // -------------------------------------------------------------------------
    // 外部复位键直接驱动这条链的异步清零端，而不是在输出上与：这样两路复位的
    // 撤销都经过同一个同步器，释放沿不会带着亚稳态进入各时钟域。
    // -------------------------------------------------------------------------
    wire rst_any_n = rst_n & ext_rst_n;      // 任一路拉低都复位

    reg [RST_SYNC_CYCLES-1:0] rst_sync_chain;

    always @(posedge clk_50m or negedge rst_any_n) begin
        if (!rst_any_n) begin
            // 异步复位：立即清零，rst_sys_n 立刻有效，不等待时钟
            rst_sync_chain <= {RST_SYNC_CYCLES{1'b0}};
        end else begin
            // 同步释放：串行移入 1'b1，RST_SYNC_CYCLES 拍后最高位为 1
            rst_sync_chain <= {rst_sync_chain[RST_SYNC_CYCLES-2:0], 1'b1};
        end
    end

    assign rst_sys_n = rst_sync_chain[RST_SYNC_CYCLES-1];

endmodule

// =============================================================================
// 全国大学生嵌入式芯片与系统设计竞赛 - 选题一 (J280 姿态控制系统竞赛套件)
// 模块名称: oled_disp
// 目标芯片: 高云 GW2A-LV55PG484C8/I7
// 功能描述: OLED 显示内容组织模块（5 行、8px 字距）
//           1. 组织 5 行文本：MODE / CUR / SET / PEND / STAT
//           2. 按 5x7 字模渲染成 SSD1306 一帧位图并写入帧缓冲
//           3. 显示刷新在后台进行，不阻塞控制环
// =============================================================================
//
// 版面设计（128x64，每格 5x7 字模 + 3 列空白）：
//   · 行数 5：MODE / CUR / SET / PEND / STAT，字距 8 像素（5 列字模 + 3 列空白）
//   · 行距按整页留白：用页 0/2/3/4/6，页 1/5/7 整页留空
//   · 左边距 12 像素、右边距 12 像素，13 格 × 8 = 104 像素居中
//
//   屏上布局（每行 13 格）：
//
//      MODE : BAL           <- 页 0
//      ................     <- 页 1（空）
//      CUR  : -01234        <- 页 2
//      SET  : +00000        <- 页 3
//      PEND : +00500        <- 页 4
//      ................     <- 页 5（空）
//      STAT : RUN   M       <- 页 6
//      ................     <- 页 7（空）
//
//   列位（13 格，每格 8 列）：
//      格 0..3 = 标签 4 字符，格 4 = 空格，格 5 = ':'（冒号固定在第 5 格）
//      格 6 = 空格，格 7 = 符号 '+'/'-'，格 8..12 = 五位数字（不足补 0）
//      MODE 行格 7..11 = IDLE / SWING / BAL
//      STAT 行格 7..10 = RUN / STOP，格 11 = 故障 '!'，格 12 = 编辑态 'M'
//
//   数字一律 5 位带符号：正数（含 0）显示 '+'，负数显示 '-'，不存在无符号行。
//
//   整帧 8 页 x 128 列 = 1024 字节全部重写，不只写用到的区域：
//   帧缓冲在 oled_ssd1306 里是一块 BSRAM，上电内容未定义，若只写用到的格子，
//   空页与左右边距会残留上电随机点阵（看起来像花屏）。
//   1024 拍 @50MHz = 20.5us，相对一帧 46.5ms 的数据发送时间可以忽略。
// =============================================================================

`timescale 1ns/1ps

module oled_disp (
    input  wire               clk,
    input  wire               rst_n,

    //---------------------------------------------------------------------
    // 显示数据快照（frame_req 时统一锁存，保证一帧之内用的是同一时刻的值）
    //---------------------------------------------------------------------
    input  wire [1:0]         mode,        // 0=IDLE 1=SWING 2=BALANCE
    input  wire signed [15:0] cur_cnt,     // pos_rel   摆臂位置（相对零位）
    input  wire signed [15:0] set_cnt,     // x_settle  定点目标
    input  wire signed [15:0] pend_cnt,    // pos_pend  待发送增量
    input  wire               run_flag,    // 运行中
    input  wire               fault_flag,  // 限位/保护触发
    //---------------------------------------------------------------------
    // 编辑态指示（顶层接 编辑/正弦模式）
    //---------------------------------------------------------------------
    input  wire               edit_flag,

    //---------------------------------------------------------------------
    // 帧缓冲写口（帧缓冲本体在 oled_ssd1306 里，那里才是被 I2C 读走的地方）
    //---------------------------------------------------------------------
    output reg  [9:0]         fb_addr,
    output reg  [7:0]         fb_data,
    output reg                fb_we,

    //---------------------------------------------------------------------
    // 与 oled_ssd1306 的握手
    //---------------------------------------------------------------------
    input  wire               frame_req,   // 1 拍：请渲染一帧
    output reg                disp_done    // 1 拍：渲染完成，可以开始送 I2C
);

    //=========================================================================
    // 版面常量
    //=========================================================================
    localparam integer LINES          = 5;    // 行数
    localparam integer CHARS_PER_LINE = 13;   // 每行格数（标签 6 + 空格 + 符号 + 5 位）
    localparam integer X0             = 12;   // 左边距（像素）
    localparam integer PITCH          = 8;    // 字距（像素）：5 列字模 + 3 列空白
    localparam integer TXT_W          = CHARS_PER_LINE * PITCH;   // 104

    //-------------------------------------------------------------------------
    // 行号 -> 页号 映射：页 1 / 5 / 7 整页留空当行距
    //   行 0 MODE -> 页 0
    //   行 1 CUR  -> 页 2
    //   行 2 SET  -> 页 3
    //   行 3 PEND -> 页 4
    //   行 4 STAT -> 页 6
    //-------------------------------------------------------------------------
    function [2:0] row2pg;
        input [2:0] r;
        begin
            case (r)
            3'd0:    row2pg = 3'd0;   // MODE
            3'd1:    row2pg = 3'd2;   // CUR
            3'd2:    row2pg = 3'd3;   // SET
            3'd3:    row2pg = 3'd4;   // PEND
            default: row2pg = 3'd6;   // STAT
            endcase
        end
    endfunction

    //=========================================================================
    // 字符行缓冲：5 行 x 13 字符 = 65 字节
    //=========================================================================
    reg  [7:0] lbuf [0:64];

    //=========================================================================
    // 显示数据的锁存副本
    //=========================================================================
    reg [1:0]         s_mode;
    reg signed [15:0] s_cur, s_set, s_pend;
    reg               s_run, s_fault, s_edit;

    //=========================================================================
    // 数字格式化：一次只转一个数，用 num_sel 选当前要转哪个
    //=========================================================================
    reg  [1:0]         num_sel;      // 0=CUR 1=SET 2=PEND
    reg  signed [17:0] num_val;
    reg                num_start;
    wire               num_busy, num_done, num_neg;
    wire [3:0]         nd4, nd3, nd2, nd1, nd0;

    always @* begin
        case (num_sel)
        2'd0:    num_val = {{2{s_cur[15]}},  s_cur};       // 符号扩展
        2'd1:    num_val = {{2{s_set[15]}},  s_set};
        default: num_val = {{2{s_pend[15]}}, s_pend};
        endcase
    end

    numfmt u_numfmt (
        .clk   (clk),
        .rst_n (rst_n),
        .start (num_start),
        .value (num_val),
        .busy  (num_busy),
        .done  (num_done),
        .neg   (num_neg),
        .d4    (nd4),
        .d3    (nd3),
        .d2    (nd2),
        .d1    (nd1),
        .d0    (nd0)
    );

    //=========================================================================
    // 文本常量
    //=========================================================================
    reg [39:0] mode_txt;    // 5 字符
    reg [31:0] stat_txt;    // 4 字符

    always @* begin
        case (s_mode)
        2'd0:    mode_txt = "IDLE ";
        2'd1:    mode_txt = "SWING";
        default: mode_txt = "BAL  ";
        endcase
    end

    always @* stat_txt = s_run ? "RUN " : "STOP";

    //=========================================================================
    // 标签常量（每行前 4 个字符）；冒号固定在第 5 格，所以标签统一补足 4 字符
    //=========================================================================
    reg [3:0]  fst;
    reg [6:0]  clr_cnt;      // 清缓冲计数 0..64
    reg [2:0]  li_fmt;       // 格式化阶段的行号 0..4
    reg [3:0]  ci_fmt;       // 格式化阶段的列号 0..12
    reg [1:0]  nfield;       // 第几个数字字段 0..2
    reg [2:0]  nwr_cnt;      // 数字写入步 0..5（1=符号，2..6=五位）
    reg [2:0]  r_pg;         // 渲染：当前页 0..7
    reg [6:0]  r_col;        // 渲染：当前列 0..127

    reg [31:0] label_txt;
    always @* begin
        case (li_fmt)
        3'd0:    label_txt = "MODE";
        3'd1:    label_txt = "CUR ";
        3'd2:    label_txt = "SET ";
        3'd3:    label_txt = "PEND";
        default: label_txt = "STAT";
        endcase
    end

    //=========================================================================
    // 状态机编码
    //=========================================================================
    localparam [3:0] F_IDLE   = 4'd0,   // 等 frame_req
                     F_CLR    = 4'd1,   // 清行缓冲（65 拍）
                     F_LBL    = 4'd2,   // 写 5 行标签 "XXXX :"
                     F_NUMSTR = 4'd3,   // 启动一次 numfmt
                     F_NUMWAI = 4'd4,   // 等 numfmt 完成
                     F_NUMWR  = 4'd5,   // 写符号 + 5 位数字
                     F_MODE   = 4'd6,   // 行 0 写模式名
                     F_STAT   = 4'd7,   // 行 4 写运行状态
                     F_REND   = 4'd8,   // 整帧渲染 8 页 x 128 列
                     F_DONE   = 4'd9;   // 输出 disp_done

    // 行缓冲地址 = li*13 + ci
    wire [6:0] lb_wa = {4'd0, li_fmt} * 7'd13 + {3'd0, ci_fmt};

    //=========================================================================
    // 渲染阶段的组合逻辑：由（页, 列）反推该字节该是什么
    //=========================================================================
    // 当前页对应的逻辑行号；空页给 0（内容会被 pg_blank 屏蔽）
    wire [2:0] pg_row   = (r_pg == 3'd0) ? 3'd0 :
                          (r_pg == 3'd2) ? 3'd1 :
                          (r_pg == 3'd3) ? 3'd2 :
                          (r_pg == 3'd4) ? 3'd3 : 3'd4;

    // 页 1 / 5 / 7 是行距留白，整页清 0
    wire       pg_blank = (r_pg == 3'd1) || (r_pg == 3'd5) || (r_pg == 3'd7);

    // 列偏移与"是否落在文本区"
    wire [7:0] col_off  = {1'b0, r_col} - 8'd12;                 // X0 = 12
    wire       col_in   = (r_col >= 7'd12) && (r_col < 7'd116);  // 12 .. 12+104-1

    wire [3:0] r_ci     = col_off[6:3];      // 第几格（0..12）
    wire [2:0] r_ki     = col_off[2:0];      // 格内第几列（0..7）

    // 行缓冲读地址；只在文本区内取值，避免越界读出 X
    wire [6:0] lb_ra    = col_in ? ({4'd0, pg_row} * 7'd13 + {3'd0, r_ci}) : 7'd0;
    wire [7:0] lb_rd    = lbuf[lb_ra];

    //=========================================================================
    // 5x7 字模
    // ---------------------------------------------------------------------
    // 字模表只被本模块使用，直接内嵌在这里
    //=========================================================================
    // 字形表：每个字符拼成一个 40 位常量，高位 = 第 0 列
    reg [39:0] g;

    always @* begin
        case (lb_rd)
            8'h20: g = 40'h0000000000;    // ' '
            8'h21: g = 40'h00005F0000;    // '!'
            8'h22: g = 40'h0000000000;    // '"'
            8'h23: g = 40'h0000000000;    // '#'
            8'h24: g = 40'h0000000000;    // '$'
            8'h25: g = 40'h2313086462;    // '%'
            8'h26: g = 40'h0000000000;    // '&'
            8'h27: g = 40'h0000000000;    // '''
            8'h28: g = 40'h001C224100;    // '('
            8'h29: g = 40'h0041221C00;    // ')'
            8'h2A: g = 40'h2A1C3E1C2A;    // '*'
            8'h2B: g = 40'h08083E0808;    // '+'
            8'h2C: g = 40'h0040301000;    // ','
            8'h2D: g = 40'h0808080808;    // '-'
            8'h2E: g = 40'h0000606000;    // '.'
            8'h2F: g = 40'h2010080402;    // '/'
            8'h30: g = 40'h3E5149453E;    // '0'
            8'h31: g = 40'h00427F4000;    // '1'
            8'h32: g = 40'h4261514946;    // '2'
            8'h33: g = 40'h2141454B31;    // '3'
            8'h34: g = 40'h1814127F10;    // '4'
            8'h35: g = 40'h2745454539;    // '5'
            8'h36: g = 40'h3C4A494930;    // '6'
            8'h37: g = 40'h0171090503;    // '7'
            8'h38: g = 40'h3649494936;    // '8'
            8'h39: g = 40'h064949291E;    // '9'
            8'h3A: g = 40'h0000363600;    // ':'
            8'h3B: g = 40'h0040361600;    // ';'
            8'h3C: g = 40'h0814224100;    // '<'
            8'h3D: g = 40'h1414141414;    // '='
            8'h3E: g = 40'h0041221408;    // '>'
            8'h3F: g = 40'h0201510906;    // '?'
            8'h40: g = 40'h3E415D551E;    // '@'
            8'h41: g = 40'h7E0909097E;    // 'A'
            8'h42: g = 40'h7F49494936;    // 'B'
            8'h43: g = 40'h3E41414122;    // 'C'
            8'h44: g = 40'h7F4141413E;    // 'D'
            8'h45: g = 40'h7F49494941;    // 'E'
            8'h46: g = 40'h7F09090901;    // 'F'
            8'h47: g = 40'h3E4149493A;    // 'G'
            8'h48: g = 40'h7F0808087F;    // 'H'
            8'h49: g = 40'h00417F4100;    // 'I'
            8'h4A: g = 40'h2040413F01;    // 'J'
            8'h4B: g = 40'h7F08142241;    // 'K'
            8'h4C: g = 40'h7F40404040;    // 'L'
            8'h4D: g = 40'h7F020C027F;    // 'M'
            8'h4E: g = 40'h7F0408107F;    // 'N'
            8'h4F: g = 40'h3E4141413E;    // 'O'
            8'h50: g = 40'h7F09090906;    // 'P'
            8'h51: g = 40'h3E4151215E;    // 'Q'
            8'h52: g = 40'h7F09192946;    // 'R'
            8'h53: g = 40'h4649494931;    // 'S'
            8'h54: g = 40'h01017F0101;    // 'T'
            8'h55: g = 40'h3F4040403F;    // 'U'
            8'h56: g = 40'h1F2040201F;    // 'V'
            8'h57: g = 40'h7F2018207F;    // 'W'
            8'h58: g = 40'h6314081463;    // 'X'
            8'h59: g = 40'h0304780403;    // 'Y'
            8'h5A: g = 40'h6151494543;    // 'Z'
            8'h5B: g = 40'h007F414100;    // '['
            8'h5C: g = 40'h0204081020;    // '\'
            8'h5D: g = 40'h0041417F00;    // ']'
            8'h5E: g = 40'h0402010204;    // '^'
            8'h5F: g = 40'h4040404040;    // '_'
            default: g = 40'h0000000000;
        endcase
    end

    //-----------------------------------------------------------------------
    // 列选择：idx 0..4 取对应列，其余给 0（字符格右侧的空白列）
    //-----------------------------------------------------------------------
    reg  [7:0] font_col;     // 当前列的 8 位点阵（bit0 最上）
    always @* begin
        case (r_ki)
            3'd0:    font_col = g[39:32];
            3'd1:    font_col = g[31:24];
            3'd2:    font_col = g[23:16];
            3'd3:    font_col = g[15:8];
            3'd4:    font_col = g[7:0];
            default: font_col = 8'h00;     // 格内第 5/6/7 列是字距空白
        endcase
    end

    // 该字节最终值：非文本区 / 空页 / 字距空白 一律 0
    wire [7:0] rend_byte = (!col_in || pg_blank) ? 8'h00 : font_col;

    //=========================================================================
    // 当前正在写的字符
    //=========================================================================
    reg [7:0] wr_ch;
    always @* begin
        wr_ch = 8'h20;                                  // 默认空格
        case (fst)
        F_LBL: begin
            if (ci_fmt <= 4'd3)      wr_ch = label_txt[(4'd3 - ci_fmt[1:0]) * 8 +: 8];
            else if (ci_fmt == 4'd4) wr_ch = 8'h20;      // ' '
            else                     wr_ch = 8'h3A;      // ':'
        end
        default: wr_ch = 8'h20;
        endcase
    end

    //-------------------------------------------------------------------------
    // 各文本段的字符选择（分开写，避免上面那个 case 里的索引越界）
    //-------------------------------------------------------------------------
    wire [3:0] mode_idx = ci_fmt - 4'd7;      // 0..4
    wire [3:0] stat_idx = ci_fmt - 4'd7;      // 0..3

    reg [7:0] mode_ch, stat_ch;
    always @* mode_ch = mode_txt[(3'd4 - mode_idx[2:0]) * 8 +: 8];
    always @* stat_ch = stat_txt[(2'd3 - stat_idx[1:0]) * 8 +: 8];
    // 索引上限写成 4'd8：8 需要 4 位，写成 3'd8 会被截成 0 而取错字符

    // 数字字符：0~9 -> '0'~'9'
    function [7:0] dig2asc;
        input [3:0] d;
        begin
            dig2asc = {4'h3, d};        // 0x30 + d
        end
    endfunction

    // 当前该写的数字（按 ci_fmt = 8..12 选万/千/百/十/个）
    reg [3:0] dsel;
    always @* begin
        case (ci_fmt)
        4'd8:    dsel = nd4;
        4'd9:    dsel = nd3;
        4'd10:   dsel = nd2;
        4'd11:   dsel = nd1;
        default: dsel = nd0;
        endcase
    end

    //=========================================================================
    // 主状态机
    //=========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            fst       <= F_IDLE;
            fb_we     <= 1'b0;
            fb_addr   <= 10'd0;
            fb_data   <= 8'd0;
            disp_done <= 1'b0;
            clr_cnt   <= 7'd0;
            li_fmt    <= 3'd0;
            ci_fmt    <= 4'd0;
            nfield    <= 2'd0;
            nwr_cnt   <= 3'd0;
            num_sel   <= 2'd0;
            num_start <= 1'b0;
            r_pg      <= 3'd0;
            r_col     <= 7'd0;
            s_mode    <= 2'd0;
            s_cur     <= 16'sd0;
            s_set     <= 16'sd0;
            s_pend    <= 16'sd0;
            s_run     <= 1'b0;
            s_fault   <= 1'b0;
            s_edit    <= 1'b0;
        end
        else begin
            fb_we     <= 1'b0;
            disp_done <= 1'b0;
            num_start <= 1'b0;

            case (fst)
            //-----------------------------------------------------------------
            // 等渲染许可；锁存所有显示数据，保证整帧一致
            //-----------------------------------------------------------------
            F_IDLE: begin
                if (frame_req) begin
                    s_mode  <= mode;
                    s_cur   <= cur_cnt;
                    s_set   <= set_cnt;
                    s_pend  <= pend_cnt;
                    s_run   <= run_flag;
                    s_fault <= fault_flag;
                    s_edit  <= edit_flag;
                    clr_cnt <= 7'd0;
                    fst     <= F_CLR;
                end
            end
            //-----------------------------------------------------------------
            F_CLR: begin
                lbuf[clr_cnt] <= 8'h20;
                if (clr_cnt == 7'd64) begin
                    li_fmt <= 3'd0;
                    ci_fmt <= 4'd0;
                    fst    <= F_LBL;
                end
                else clr_cnt <= clr_cnt + 7'd1;
            end
            //-----------------------------------------------------------------
            // 行 0..4 每行写 6 个字符："XXXX" + ' ' + ':'
            //-----------------------------------------------------------------
            F_LBL: begin
                lbuf[lb_wa] <= wr_ch;
                if (ci_fmt == 4'd5) begin
                    ci_fmt <= 4'd0;
                    if (li_fmt == 3'd4) begin
                        nfield  <= 2'd0;
                        num_sel <= 2'd0;
                        fst     <= F_NUMSTR;
                    end
                    else li_fmt <= li_fmt + 3'd1;
                end
                else ci_fmt <= ci_fmt + 4'd1;
            end
            //-----------------------------------------------------------------
            // 依次格式化 3 个数字，写进行 1..3：格 7 符号，格 8..12 五位
            //-----------------------------------------------------------------
            F_NUMSTR: begin
                num_sel   <= nfield;
                num_start <= 1'b1;
                fst       <= F_NUMWAI;
            end
            F_NUMWAI: begin
                if (num_done) begin
                    li_fmt  <= {1'b0, nfield} + 3'd1;   // 行号 1..3
                    ci_fmt  <= 4'd7;                    // 先写符号位
                    nwr_cnt <= 3'd1;
                    fst     <= F_NUMWR;
                end
            end
            F_NUMWR: begin
                if (nwr_cnt == 3'd1 && ci_fmt == 4'd7) begin
                    // 符号位：负数 '-'，正数（含 0）'+'
                    lbuf[lb_wa] <= num_neg ? 8'h2D : 8'h2B;
                    ci_fmt  <= 4'd8;
                    nwr_cnt <= 3'd2;
                end
                else begin
                    lbuf[lb_wa] <= dig2asc(dsel);
                    if (ci_fmt == 4'd12) begin
                        if (nfield == 2'd2) begin
                            li_fmt <= 3'd0;
                            ci_fmt <= 4'd7;          // 模式名从第 7 格开始
                            fst    <= F_MODE;
                        end
                        else begin
                            nfield <= nfield + 2'd1;
                            fst    <= F_NUMSTR;
                        end
                    end
                    else begin
                        ci_fmt  <= ci_fmt + 4'd1;
                        nwr_cnt <= nwr_cnt + 3'd1;
                    end
                end
            end
            //-----------------------------------------------------------------
            // 行 0 格 7..11：模式名（IDLE / SWING / BAL）
            //-----------------------------------------------------------------
            F_MODE: begin
                lbuf[lb_wa] <= mode_ch;
                if (ci_fmt == 4'd11) begin
                    ci_fmt <= 4'd7;
                    li_fmt <= 3'd4;                  // 下一行写 STAT
                    fst    <= F_STAT;
                end
                else ci_fmt <= ci_fmt + 4'd1;
            end
            //-----------------------------------------------------------------
            // 行 4 格 7..12：RUN / STOP（格 7..10）、故障 '!'（格 11）、
            //               数值输入/正弦模式 'M'（格 12）
            //-----------------------------------------------------------------
            F_STAT: begin
                if (ci_fmt <= 4'd10)      lbuf[lb_wa] <= stat_ch;
                else if (ci_fmt == 4'd11) lbuf[lb_wa] <= (s_fault ? 8'h21 : 8'h20);
                else if (ci_fmt == 4'd12) lbuf[lb_wa] <= (s_edit  ? 8'h4D : 8'h20);
                else                      lbuf[lb_wa] <= 8'h20;
                if (ci_fmt == 4'd12) begin
                    ci_fmt <= 4'd0;
                    r_pg   <= 3'd0;
                    r_col  <= 7'd0;
                    fst    <= F_REND;
                end
                else ci_fmt <= ci_fmt + 4'd1;
            end
            //-----------------------------------------------------------------
            // 整帧渲染：8 页 x 128 列 = 1024 次写（含留白与左右边距）
            //-----------------------------------------------------------------
            F_REND: begin
                fb_we   <= 1'b1;
                fb_addr <= {r_pg, r_col};
                fb_data <= rend_byte;

                if (r_col == 7'd127) begin
                    r_col <= 7'd0;
                    if (r_pg == 3'd7) fst <= F_DONE;
                    else              r_pg <= r_pg + 3'd1;
                end
                else r_col <= r_col + 7'd1;
            end
            //-----------------------------------------------------------------
            F_DONE: begin
                fb_we     <= 1'b0;
                disp_done <= 1'b1;
                fst       <= F_IDLE;
            end
            //-----------------------------------------------------------------
            default: fst <= F_IDLE;
            endcase
        end
    end

endmodule

//=============================================================================
// 文件名  : tb_pid_pipeline.v
// 模块名  : tb_pid_pipeline
// 项目    : J280 旋转倒立摆 FPGA 控制系统
// 功能    : 【重点 testbench】流水线 PID 控制器自检
//-----------------------------------------------------------------------------
// 验证点（对应提示词 §4 对 pid_pipeline 的明确要求）
//   T1  复位/停机：u_ctrl=0、u_vld=0、积分清零、无饱和
//   T2  P 项正数运算（Q10 反标定正确）
//   T3  P 项负数运算（★ 有符号数处理，最容易出错的地方）
//   T4  正方向输出饱和限幅
//   T5  负方向输出饱和限幅
//   T6  ★★ 流水线延迟拍数 = 5 拍（逐拍计数实测）
//   T7  ★★ 连续输入吞吐率：每拍都产出有效输出
//   T8  D 项运算（含负数）
//   T9  位置环 P/D 项运算（含负数）
//   T10 积分累加正确性（I 项）
//   T11 积分累加器硬限幅（抗饱和策略 1）
//   T12 条件积分冻结（抗饱和策略 2）
//   T13 饱和后积分回退（验证冻结是"单向"的，不会阻止解饱和）
//   T14 run_en 拉低后积分与输出清零
//
// 判据全部为**精确数值比对**，不做"看起来差不多"的模糊判断。
// 期望值的推导过程写在各用例注释里，便于复核。
//=============================================================================

`timescale 1ns/1ns

module tb_pid_pipeline;

    //=========================================================================
    // 参数镜像（与 DUT 默认值保持一致；Q10 定点：1.0 == 1024）
    //=========================================================================
    localparam integer Q_FMT      = 10;
    localparam integer I_MAX      = 4194304;   // 32'sd4_194_304
    localparam integer OUT_MAX    = 4095;
    localparam integer LAT_EXPECT = 5;         // PIPE_STAGES

    //=========================================================================
    // DUT 信号
    //=========================================================================
    reg                    clk;
    reg                    rst_n;
    reg                    ctrl_tick;
    reg                    run_en;

    reg signed [15:0]      err_th, dth, err_x, dx;
    reg signed [15:0]      kp_th, ki_th, kd_th, kp_x, kd_x;

    wire signed [15:0]     u_ctrl;
    wire                   u_vld;
    wire                   s5_sat;

    wire signed [31:0]     s2_p_term, s2_px_term, s3_d_term, s3_dx_term;
    wire signed [31:0]     s3_i_acc;
    wire signed [35:0]     s4_sum;

    //=========================================================================
    // 计分
    //=========================================================================
    integer fail_cnt;
    integer check_cnt;

    // ---- 自检任务：整数比较 ----
    task check_i;
        input [255:0] name;
        input integer expected;
        input integer got;
        begin
            check_cnt = check_cnt + 1;
            if (expected === got) begin
                $display("[CHECK] %0s: expected=%0d, got=%0d => OK",
                         name, expected, got);
            end
            else begin
                $display("[CHECK] %0s: expected=%0d, got=%0d => FAIL",
                         name, expected, got);
                fail_cnt = fail_cnt + 1;
            end
        end
    endtask

    // ---- 产生一个控制节拍（恰好 1 个时钟宽）----
    task tick_once;
        begin
            ctrl_tick = 1'b0;
            @(posedge clk);
            ctrl_tick = 1'b1;
            @(posedge clk);
            ctrl_tick = 1'b0;
        end
    endtask

    // ---- 把所有激励清零，便于用例之间互不干扰 ----
    task clear_stim;
        begin
            err_th = 16'sd0; dth = 16'sd0; err_x = 16'sd0; dx = 16'sd0;
            kp_th  = 16'sd0; ki_th = 16'sd0; kd_th = 16'sd0;
            kp_x   = 16'sd0; kd_x  = 16'sd0;
        end
    endtask

    //=========================================================================
    // 时钟：50MHz
    //=========================================================================
    initial clk = 1'b0;
    always #10 clk = ~clk;

    //=========================================================================
    // DUT
    //=========================================================================
    pid_pipeline #(
        .Q_FMT  (Q_FMT),
        .ERR_W  (16),
        .GAIN_W (16),
        .PROD_W (32),
        .ACC_W  (32),
        .SUM_W  (36),
        .OUT_W  (16),
        .I_MAX  (32'sd4_194_304),
        .OUT_MAX(16'sd4095)
    ) dut (
        .clk        (clk),
        .rst_n      (rst_n),
        .ctrl_tick  (ctrl_tick),
        .run_en     (run_en),
        .err_th     (err_th),
        .dth        (dth),
        .err_x      (err_x),
        .dx         (dx),
        .kp_th      (kp_th),
        .ki_th      (ki_th),
        .kd_th      (kd_th),
        .kp_x       (kp_x),
        .kd_x       (kd_x),
        .u_ctrl     (u_ctrl),
        .u_vld      (u_vld),
        .s5_sat     (s5_sat),
        .s2_p_term  (s2_p_term),
        .s2_px_term (s2_px_term),
        .s3_d_term  (s3_d_term),
        .s3_dx_term (s3_dx_term),
        .s3_i_acc   (s3_i_acc),
        .s4_sum     (s4_sum)
    );

    //=========================================================================
    // 主激励
    //=========================================================================
    integer n;
    integer lat_cnt;
    integer vld_ok;
    reg [15:0] u_prev;

    initial begin
        $display("================================================================");
        $display(" tb_pid_pipeline 开始");
        $display("================================================================");

        fail_cnt  = 0;
        check_cnt = 0;

        // ---- 初始化 ----
        rst_n     = 1'b0;
        run_en    = 1'b0;
        ctrl_tick = 1'b0;
        clear_stim();

        #100;
        rst_n = 1'b1;
        #100;

        //---------------------------------------------------------------------
        // T1 复位/停机
        //---------------------------------------------------------------------
        kp_th  = 16'sd1024;          // 1.0
        err_th = 16'sd100;
        run_en = 1'b0;
        repeat (10) @(posedge clk);

        check_i("T1a 停机时 u_ctrl=0",        0, $signed(u_ctrl));
        check_i("T1b 停机时 u_vld=0",         0, u_vld);
        check_i("T1c 停机时 s3_i_acc=0",      0, $signed(s3_i_acc));
        check_i("T1d 停机时 s5_sat=0",        0, s5_sat);

        //---------------------------------------------------------------------
        // T2 P 项正数
        //   期望：u = (Kp*e) >>> Q_FMT = (1024*100) >>> 10 = 102400/1024 = 100
        //---------------------------------------------------------------------
        clear_stim();
        kp_th  = 16'sd1024;
        err_th = 16'sd100;
        run_en = 1'b1;
        repeat (12) @(posedge clk);

        check_i("T2  P项正数 Kp=1.0,e=+100 => u=+100", 100, $signed(u_ctrl));
        check_i("T2b u_vld 应有效",                    1,   u_vld);

        //---------------------------------------------------------------------
        // T3 P 项负数（有符号处理）
        //   期望：u = (1024*(-100)) >>> 10 = -100
        //   ★ 若误用逻辑右移或 /1024，这里会得到错误值
        //---------------------------------------------------------------------
        err_th = -16'sd100;
        repeat (12) @(posedge clk);
        check_i("T3  P项负数 Kp=1.0,e=-100 => u=-100", -100, $signed(u_ctrl));

        //---------------------------------------------------------------------
        // T4 正方向饱和限幅
        //   期望：Kp=8.0(8192), e=+1000 → 8,192,000 >>> 10 = 8000 > 4095 → 钳到 4095
        //---------------------------------------------------------------------
        kp_th  = 16'sd8192;
        err_th = 16'sd1000;
        repeat (12) @(posedge clk);
        check_i("T4a 正饱和 u_ctrl 钳到 +4095", 4095, $signed(u_ctrl));
        check_i("T4b 正饱和 s5_sat=1",          1,    s5_sat);

        //---------------------------------------------------------------------
        // T5 负方向饱和限幅
        //---------------------------------------------------------------------
        err_th = -16'sd1000;
        repeat (12) @(posedge clk);
        check_i("T5a 负饱和 u_ctrl 钳到 -4095", -4095, $signed(u_ctrl));
        check_i("T5b 负饱和 s5_sat=1",          1,     s5_sat);

        //---------------------------------------------------------------------
        // T6 ★★ 流水线延迟实测（逐拍计数）
        //   方法：在某个时钟沿把 err_th 从 100 改成 200（非阻塞赋值，
        //         模拟真实寄存器行为），然后逐拍等待 u_ctrl 变成 200。
        //   期望：5 拍（S1→S2→S3→S4→S5）
        //---------------------------------------------------------------------
        clear_stim();
        kp_th  = 16'sd1024;
        err_th = 16'sd100;
        run_en = 1'b1;
        repeat (12) @(posedge clk);
        check_i("T6a 延迟测量基线 u=+100", 100, $signed(u_ctrl));

        @(posedge clk);
        err_th <= 16'sd200;                 // 此处刻起，输入寄存器已更新
        lat_cnt = 0;
        // ★ 采样点必须放在 negedge（半周期后）。
        //   若在 posedge 的 active 区域立刻读 u_ctrl，此时 NBA 更新尚未提交、
        //   组合逻辑也还没重算，会读到**上一拍**的旧值，从而多算一拍。
        //   （首次运行时正是这个原因测出 6 拍而非 5 拍 —— 属于 tb 采样时机
        //     问题，不是 RTL 延迟问题。）
        @(negedge clk);
        while ((u_ctrl !== 16'sd200) && (lat_cnt < 20)) begin
            @(posedge clk);
            lat_cnt = lat_cnt + 1;
            @(negedge clk);
        end
        $display("[INFO] 实测流水线延迟 = %0d 拍 (@50MHz = %0d ns)",
                 lat_cnt, lat_cnt * 20);
        check_i("T6b 流水线延迟 = 5 拍", LAT_EXPECT, lat_cnt);
        check_i("T6c 延迟后输出值正确 u=+200", 200, $signed(u_ctrl));

        //---------------------------------------------------------------------
        // T7 ★★ 连续输入吞吐率：每拍都产出有效输出
        //   连续观察 20 拍，u_vld 必须恒为 1（流水线不停顿、不插入气泡）
        //---------------------------------------------------------------------
        vld_ok = 1;
        for (n = 0; n < 20; n = n + 1) begin
            @(posedge clk);
            if (u_vld !== 1'b1) vld_ok = 0;
        end
        check_i("T7  吞吐率：连续20拍 u_vld 恒为1", 1, vld_ok);

        //---------------------------------------------------------------------
        // T8 D 项（含负数）
        //   期望：Kd=1.0, Δθ=+50 → u = (1024*50) >>> 10 = +50
        //                Δθ=-50 → u = -50
        //---------------------------------------------------------------------
        clear_stim();
        kd_th = 16'sd1024;
        dth   = 16'sd50;
        run_en = 1'b1;
        repeat (12) @(posedge clk);
        check_i("T8a D项 Kd=1.0,dth=+50 => u=+50", 50, $signed(u_ctrl));

        dth = -16'sd50;
        repeat (12) @(posedge clk);
        check_i("T8b D项 Kd=1.0,dth=-50 => u=-50", -50, $signed(u_ctrl));

        //---------------------------------------------------------------------
        // T9 位置环 P/D 项（含负数）
        //---------------------------------------------------------------------
        clear_stim();
        kp_x  = 16'sd1024;
        err_x = 16'sd30;
        run_en = 1'b1;
        repeat (12) @(posedge clk);
        check_i("T9a 位置P Kp_x=1.0,e_x=+30 => u=+30", 30, $signed(u_ctrl));

        clear_stim();
        kd_x = 16'sd1024;
        dx   = -16'sd20;
        repeat (12) @(posedge clk);
        check_i("T9b 位置D Kd_x=1.0,dx=-20 => u=-20", -20, $signed(u_ctrl));

        //---------------------------------------------------------------------
        // T10 积分累加（I 项）
        //   期望：Ki=1.0(1024), e=+10 → 每次 tick 增量 = 1024*10 = 10240
        //         10 次 tick 后 i_acc = 102400，u = 102400>>>10 = +100
        //---------------------------------------------------------------------
        run_en = 1'b0;  repeat (6) @(posedge clk);   // 先清积分
        clear_stim();
        ki_th  = 16'sd1024;
        err_th = 16'sd10;
        run_en = 1'b1;  repeat (8) @(posedge clk);

        for (n = 0; n < 10; n = n + 1) tick_once();
        repeat (10) @(posedge clk);

        check_i("T10a 10次积分 i_acc = 10*10240", 102400, $signed(s3_i_acc));
        check_i("T10b 积分项输出 u = +100",      100,    $signed(u_ctrl));

        //---------------------------------------------------------------------
        // T11 积分累加器硬限幅（抗饱和策略 1）
        //   期望：Ki 取最大 32767, e=+1024 → 单次增量 = 33,553,408
        //         远超 I_MAX=4,194,304，必须被钳到 I_MAX 而不是溢出/继续增长
        //   ★ 这是"积分限幅"的直接证据
        //---------------------------------------------------------------------
        run_en = 1'b0;  repeat (6) @(posedge clk);   // 清积分与饱和标志
        clear_stim();
        ki_th  = 16'sd32767;
        err_th = 16'sd1024;
        run_en = 1'b1;  repeat (8) @(posedge clk);

        tick_once();
        repeat (10) @(posedge clk);

        check_i("T11 积分硬限幅 i_acc = I_MAX(4194304)", I_MAX, $signed(s3_i_acc));

        //---------------------------------------------------------------------
        // T12 条件积分冻结（抗饱和策略 2）
        //   此时输出已饱和(>>10 = 4096 > 4095)，且 i_inc>0 与饱和同向，
        //   再打 5 个 tick，i_acc 必须**保持不变**
        //---------------------------------------------------------------------
        for (n = 0; n < 5; n = n + 1) tick_once();
        repeat (10) @(posedge clk);

        check_i("T12a 饱和时积分冻结 i_acc 不变", I_MAX, $signed(s3_i_acc));
        check_i("T12b 饱和时 u 钳在 +4095",       4095,  $signed(u_ctrl));
        check_i("T12c 饱和标志 s5_sat=1",         1,     s5_sat);

        //---------------------------------------------------------------------
        // T13 饱和后积分回退（冻结必须是单向的，不能阻止解饱和）
        //   期望：e 反向取一个小值 -8 → i_inc = 32767*(-8) = -262136 < 0，
        //         与正饱和方向相反 → 冻结解除 → i_acc 应下降
        //   ★ 这里故意用小值：若用 -1024，i_inc = -33,553,808 会把积分
        //     一次性打到**负向**限幅，输出变成 -4095（负饱和），
        //     于是"脱离饱和"的断言就不成立了（首次运行即踩到这个坑）。
        //---------------------------------------------------------------------
        err_th = -16'sd8;
        repeat (6) @(posedge clk);
        $display("[INFO] T13 回退前 i_acc = %0d (I_MAX=%0d)", $signed(s3_i_acc), I_MAX);

        tick_once();
        // ★ 积分在 S3 更新，还要再穿过 S4、S5 两级才会反映到 u_ctrl 上，
        //   因此必须再等 2 拍以上。只等半个周期会读到旧的饱和输出，
        //   导致"脱离饱和"的断言误判（首次运行即如此）。
        repeat (6) @(posedge clk);
        @(negedge clk);
        $display("[INFO] T13 回退后 i_acc = %0d", $signed(s3_i_acc));
        check_i("T13a 反向误差解除积分冻结(i_acc < I_MAX)", 1,
                ($signed(s3_i_acc) < I_MAX) ? 1 : 0);
        check_i("T13b 回退后输出脱离正饱和(s5_sat=0)", 0, s5_sat);
        check_i("T13c 输出仍为正且未钳位", 1,
                ($signed(u_ctrl) > 0 && $signed(u_ctrl) < 4095) ? 1 : 0);

        //---------------------------------------------------------------------
        // T14 run_en 拉低 → 积分与输出清零
        //---------------------------------------------------------------------
        run_en = 1'b0;
        repeat (10) @(posedge clk);
        check_i("T14a 停机后 s3_i_acc=0",  0, $signed(s3_i_acc));
        check_i("T14b 停机后 u_ctrl=0",    0, $signed(u_ctrl));
        check_i("T14c 停机后 u_vld=0",     0, u_vld);
        check_i("T14d 停机后 s5_sat=0",    0, s5_sat);

        //---------------------------------------------------------------------
        // 汇总
        //---------------------------------------------------------------------
        $display("================================================================");
        $display(" 检查点总数 = %0d，失败 = %0d", check_cnt, fail_cnt);
        if (fail_cnt == 0)
            $display("TEST_RESULT: tb_pid_pipeline PASS");
        else
            $display("TEST_RESULT: tb_pid_pipeline FAIL  失败项数=%0d", fail_cnt);
        $display("================================================================");
        $finish;
    end

    //-------------------------------------------------------------------------
    // 超时保护：正常情况下上面就会 $finish；若逻辑死锁则兜底退出
    //-------------------------------------------------------------------------
    initial begin
        #2000000;
        $display("TEST_RESULT: tb_pid_pipeline FAIL  失败项数=999 (TIMEOUT)");
        $finish;
    end

endmodule
